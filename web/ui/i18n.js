export function translate(language, key, values = {}) {
  let text = messages[key]?.[language === "en" ? 1 : 0] ?? key;
  if (language === "en" && values.n === 1) {
    const singular = { queries: "1 query", records: "1 record", points: "1 point" };
    if (singular[key]) return singular[key];
  }
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, value);
  return text;
}

export function applyLanguage(language) {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(language, element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = translate(language, element.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(language, element.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-prompt-key]").forEach((element) => {
    element.dataset.prompt = translate(language, element.dataset.promptKey);
  });
}
